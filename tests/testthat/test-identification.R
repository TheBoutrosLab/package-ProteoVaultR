test_that("shared proteins do not multiply PSMs and optional layers are explicit", {
    vault <- open_vault(make_test_vault())
    on.exit(close_vault(vault), add = TRUE)
    rows <- dplyr::collect(tbl_psms(vault))
    expect_equal(nrow(rows), 1L)
    expect_equal(rows$sequence, "PEPTIDE")
    expect_equal(rows$sample_name, "S1")
    expect_equal(rows$rt_seconds, 120)
    expect_equal(nrow(dplyr::collect(tbl_psm_scores(vault))), 2L)
    expect_error(tbl_psms(vault, stage = "search"), "--layer raw-search")
    expect_error(tbl_vault(vault, "pin_features"), "--layer msbooster")
    expect_error(tbl_vault(vault, "psm_features"), "--layer raw-search")
})

test_that("extended layers preserve stage scores and empty imports remain available", {
    path <- make_test_vault(optional = TRUE)
    vault <- open_vault(path)
    expect_equal(vault_info(vault)$layers, c("core", "msbooster", "raw-search"))
    expect_equal(nrow(dplyr::collect(tbl_psms(vault))), 1L)
    expect_equal(nrow(dplyr::collect(tbl_psms(vault, stage = c("validation", "search")))), 2L)
    raw <- dplyr::collect(tbl_psm_scores(vault, stage = "search"))
    expect_equal(raw$name, "hyperscore")
    expect_true(raw$higher_better)
    close_vault(vault)
    edit_test_vault(path, "DELETE FROM pin_features")
    vault <- open_vault(path)
    on.exit(close_vault(vault), add = TRUE)
    expect_equal(nrow(dplyr::collect(tbl_vault(vault, "pin_features"))), 0L)
})
