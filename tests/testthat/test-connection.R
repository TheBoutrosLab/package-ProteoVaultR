test_that("connections are read-only and closing is idempotent", {
    path <- make_test_vault()
    vault <- open_vault(path = path)
    expect_s3_class(vault, "proteovault")
    expect_error(DBI::dbExecute(vault_connection(vault), "DELETE FROM metadata"))
    info <- vault_info(vault)
    expect_equal(info$analysis$dataset_id, "TEST")
    expect_equal(info$layers, "core")
    expect_s3_class(info$sources$mtime_ns, "integer64")
    expect_output(print(vault), "TEST")
    tables <- list_vault_tables(vault)
    expect_type(tables, "character")
    expect_identical(tables, sort(tables))
    expect_true(all(c("samples", "protein_quant_long") %in% tables))
    expect_equal(nrow(dplyr::collect(tbl_vault(vault, "samples"))), 3L)
    close_vault(vault)
    expect_no_error(close_vault(vault))
    expect_error(tbl_protein_quant(vault), "closed")
    expect_error(vault_info(vault), "closed")
    expect_error(list_vault_tables(vault), "closed")
})

test_that("missing paths are not created and unowned connections stay open", {
    missing <- tempfile(fileext = ".duckdb")
    expect_error(open_vault(path = missing))
    expect_false(file.exists(missing))
    first <- open_vault(path = make_test_vault())
    second <- open_vault(path = make_test_vault())
    close_vault(first)
    expect_true(DBI::dbIsValid(vault_connection(second)))
    close_vault(second)
})
