test_that("inference and quantification groups and group types remain distinct", {
    vault <- open_vault(make_test_vault())
    on.exit(close_vault(vault), add = TRUE)
    groups <- tbl_protein_groups(vault, method = "ProteinProphet", group_type = "protein_group")
    expect_s3_class(groups, "tbl_lazy")
    rows <- dplyr::collect(groups)
    expect_equal(rows$group_id, 93)
    expect_equal(rows$score, .9)
    expect_equal(rows$score_type, "probability")
    members <- dplyr::collect(tbl_group_members(vault, source_id = 105, group_type = "protein_group"))
    expect_equal(sort(members$accession), c("P1", "P2"))
    expect_equal(unique(members$method), "ProteinProphet")
    quantities <- dplyr::collect(tbl_protein_quant(vault))
    expect_equal(unique(quantities$grouping_method), "DIA-NN")
    expect_equal(nrow(quantities), 4L)
})
